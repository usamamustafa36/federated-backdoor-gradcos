#!/usr/bin/env python3
"""P3X (iterations/PREREG_P3X.md): do P3's exploratory detection effects replicate on
held-out seeds?  Writes paper/numbers_p3x.tex.  Do not change the cells or signs below
without an amendment to the pre-registration.

X1: pooled sigma_k * [DR_fix - DR_def] > 0 over h1-h4, exact one-sided sign-flip.
X2: the same with Youden J = DR - FPR.
X3: FoolsGold IID s47-51 attacked BSR, fixed - defect (descriptive, predicted +).
"""
import argparse
import itertools
import json
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))

CELLS = [  # id, rule, partition, seeds, sigma
    ("h1", "fldetector", "dirichlet", range(47, 52), +1),
    ("h2", "alignins", "dirichlet", range(47, 52), +1),
    ("h3", "alignins", "iid", range(43, 47), -1),
    ("h4", "foolsgold", "iid", range(47, 52), -1),
]
N_REGISTERED = sum(len(c[3]) for c in CELLS)


def load(res, mode, part, rule, seed):
    f = os.path.join(res, f"p3{mode}_{part}_ciciot2023_{rule}_atk1_m0.2_p0.1_fixed_me15_sm_s{seed}.json")
    if not os.path.exists(f) or os.path.getsize(f) == 0:
        return None
    h = json.load(open(f))["history"]
    if len(h["accuracy"]) < 15:
        return None
    last = lambda k: sum(h[k][-5:]) / 5.0
    return {"DR": last("detection_rate"), "FPR": last("false_positive_rate"), "BSR": last("bsr")}


def signflip_p(d):
    """Exact one-sided p of sum(d) >= observed under random sign flips."""
    d = [x for x in d if x != 0]
    if not d:
        return 1.0
    obs = sum(d)
    n = len(d)
    if n > 22:
        raise SystemExit("too many pairs for exact enumeration")
    cnt = 0
    for signs in itertools.product((1, -1), repeat=n):
        if sum(s * abs(x) for s, x in zip(signs, d)) >= obs - 1e-12:
            cnt += 1
    return cnt / 2 ** n


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--res", default="results/postfix_p3")
    ap.add_argument("--out", default="paper/numbers_p3x.tex")
    a = ap.parse_args()
    import p3x_blind  # Amendment 1 (iteration 32): no outcome is read before the set is complete
    assert [(c[0], c[1], c[2], list(c[3]), c[4]) for c in CELLS] == \
        [(c[0], c[1], c[2], list(c[3]), c[4]) for c in p3x_blind.CELLS]
    if not p3x_blind.unblinded(a.res):
        n = p3x_blind.pairs_present(a.res)
        with open(a.out, "w") as fh:
            fh.write("% Generated by paper/analyse_p3x.py (iterations/PREREG_P3X.md). Do not edit.\n"
                     "% Blinded (Amendment 1): outcomes withheld until all registered pairs exist.\n")
            mac = {"pxNReg": str(N_REGISTERED), "pxXOneN": str(n), "pxXTwoN": str(n),
                   "pxFinal": "blinded", "pxXThreeN": r"\PENDING"}
            for k in ("HOne", "HTwo", "HThree", "HFour"):
                for t in ("N", "Def", "Fix", "Agree"):
                    mac[f"px{k}{t}"] = r"\PENDING"
            for name in ("XOne", "XTwo"):
                for t in ("P", "Pos", "Neg", "Sup"):
                    mac[f"px{name}{t}"] = r"\PENDING"
            for t in ("Def", "Fix", "Pos"):
                mac[f"pxXThree{t}"] = r"\PENDING"
            for k in sorted(mac):
                fh.write(f"\\providecommand{{\\{k}}}{{{mac[k]}}}\n")
        print(f"P3X: blinded, {n}/{N_REGISTERED} registered pairs complete; no outcome read")
        return
    mac = {}
    dX1, dX2 = [], []
    for cid, rule, part, seeds, sg in CELLS:
        rows = []
        for s in seeds:
            de, fx = load(a.res, "full", part, rule, s), load(a.res, "trainable", part, rule, s)
            if de is None or fx is None:
                continue
            rows.append((de, fx))
            dX1.append(sg * (fx["DR"] - de["DR"]))
            dX2.append(sg * ((fx["DR"] - fx["FPR"]) - (de["DR"] - de["FPR"])))
        k = {"h1": "HOne", "h2": "HTwo", "h3": "HThree", "h4": "HFour"}[cid]
        n = len(rows)
        mac[f"px{k}N"] = str(n)
        if n:
            md = sum(r[0]["DR"] for r in rows) / n
            mf = sum(r[1]["DR"] for r in rows) / n
            mac[f"px{k}Def"] = f"{md:.2f}"
            mac[f"px{k}Fix"] = f"{mf:.2f}"
            mac[f"px{k}Agree"] = str(sum(1 for r in rows if sg * (r[1]["DR"] - r[0]["DR"]) > 0))
        else:
            for t in ("Def", "Fix", "Agree"):
                mac[f"px{k}{t}"] = r"\PENDING"
    final = len(dX1) == N_REGISTERED
    for name, d in (("XOne", dX1), ("XTwo", dX2)):
        mac[f"px{name}N"] = str(len(d))
        if d:
            p = signflip_p(d)
            mac[f"px{name}P"] = f"{p:.2g}" if p >= 1e-3 else f"{p:.1e}".replace("e-0", r"\times10^{-") + "}"
            mac[f"px{name}Pos"] = str(sum(1 for x in d if x > 0))
            mac[f"px{name}Neg"] = str(sum(1 for x in d if x < 0))
            mac[f"px{name}Sup"] = "supported" if p <= 0.05 else "not supported"
        else:
            for t in ("P", "Pos", "Neg", "Sup"):
                mac[f"px{name}{t}"] = r"\PENDING"
    # X3: FoolsGold IID BSR, s47-51
    b = []
    for s in range(47, 52):
        de, fx = load(a.res, "full", "iid", "foolsgold", s), load(a.res, "trainable", "iid", "foolsgold", s)
        if de and fx:
            b.append((de["BSR"], fx["BSR"]))
    mac["pxXThreeN"] = str(len(b))
    if b:
        mac["pxXThreeDef"] = f"{sum(x[0] for x in b) / len(b):.3f}"
        mac["pxXThreeFix"] = f"{sum(x[1] for x in b) / len(b):.3f}"
        mac["pxXThreePos"] = str(sum(1 for x in b if x[1] > x[0]))
    else:
        for t in ("Def", "Fix", "Pos"):
            mac[f"pxXThree{t}"] = r"\PENDING"
    mac["pxNReg"] = str(N_REGISTERED)
    mac["pxFinal"] = "final" if final else "interim"
    with open(a.out, "w") as fh:
        fh.write("% Generated by paper/analyse_p3x.py (iterations/PREREG_P3X.md). Do not edit.\n")
        for k in sorted(mac):
            fh.write(f"\\providecommand{{\\{k}}}{{{mac[k]}}}\n")
    print(f"P3X: X1 n={len(dX1)}/{N_REGISTERED} p={mac['pxXOneP']} ({mac['pxXOneSup']}); "
          f"X2 p={mac['pxXTwoP']}; X3 n={len(b)}; {mac['pxFinal']}")


if __name__ == "__main__":
    main()
