"""Seed-robust attack calibration (iteration 6) -> paper/numbers_calib6.tex (\\cs... macros).

Sources (all written by code in this repo; nothing typed by hand):
  results/calib_iter6/mal_shares.json      experiments/calib_iter6/shares.py: malicious data
                                           share per seed, random vs share-matched selection
  results/calib_iter6/calib6_dirichlet_*   experiments/calib_iter6/run_calib.sh: FedAvg,
                                           copy fix ON, P3 scale, attacked, per seed/variant
  results/postfix_p2/p2full_dirichlet_*fedavg_atk1*   the P2 attack (random selection,
                                           E_m=5) per seed, FedAvg
  results/postfix_p1/p1full_dirichlet_*fedavg_atk0*   clean FedAvg per seed (BSR floor)
  results/foolsgold_diag/fgdiag_*.json     experiments/foolsgold_diag/diag.py
CA/BSR: means over the last five rounds; implant: first round with BSR > 0.5.
Missing -> \\PENDING.
"""
from __future__ import annotations

import glob
import json
import math
import os

import numpy as np

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
R = lambda *p: os.path.join(ROOT, "results", *p)
OUT = os.path.join(ROOT, "paper", "numbers_calib6.tex")
TAIL = 5
SEEDS = {42: "FortyTwo", 43: "FortyThree", 44: "FortyFour", 45: "FortyFive",
         46: "FortySix", 47: "FortySeven", 48: "FortyEight", 49: "FortyNine",
         50: "Fifty", 51: "FiftyOne"}
# The stopped P1/P2 campaigns ran seeds 42-46 only; their reference columns are
# "not run" (n/r) for later seeds rather than pending.
P12_SEEDS = {42, 43, 44, 45, 46}
# run_sweep filename suffix (between "_fixed" and "_s<seed>") -> macro stem
VARIANTS = {"_me5_sm": "SmEfive", "_me8_sm": "SmEeight", "_me10_sm": "SmEten", "_me15_sm": "SmEfifteen",
            "_ms80_sm": "SmSeighty", "_me5_ms80_sm": "SmSeighty",
            "_me5_ms120_sm": "SmSonetwenty", "_ms120_sm": "SmSonetwenty"}


# stems the manuscript's Table tab:seedcal reads: always defined (\\PENDING if not run)
REQUIRED = {"SmEfive", "SmEten", "SmEfifteen"}
# p=0.1 only: the two p=0.3 side cells (s44, s46 at E_m=5; BSR at the floor) share the
# _me5_sm suffix and must not overwrite the p=0.1 cells.


def tail(xs):
    xs = [x for x in xs[-TAIL:] if x is not None and not math.isnan(x)]
    return float(np.mean(xs)) if xs else float("nan")


def f3(x):
    return "\\PENDING" if x is None or (isinstance(x, float) and math.isnan(x)) else f"{x:.3f}"


def pct(x):
    return "\\PENDING" if x is None or math.isnan(x) else f"{100 * x:.1f}\\%"


def cell(path):
    try:
        d = json.load(open(path))
    except (OSError, json.JSONDecodeError):
        return None
    h = d["history"]
    imp = next((r for r, b in zip(h["rounds"], h["bsr"]) if b > 0.5), None)
    return dict(ca=tail(h["accuracy"]), bsr=tail(h["bsr"]), imp=imp,
                share=d.get("malicious_data_share"))


def main():
    L = ["% Generated by paper/make_numbers_calib6.py. DO NOT EDIT."]
    P = lambda name, val: L.append(f"\\providecommand{{\\cs{name}}}{{{val}}}")

    # --- malicious data share under the two selection rules -------------------
    sh = json.load(open(R("calib_iter6", "mal_shares.json"))) if os.path.exists(
        R("calib_iter6", "mal_shares.json")) else None
    if sh:
        dr = [r for r in sh["rows"] if r["partition"] == "dirichlet"]
        rnd = [r["random_share"] for r in dr]
        mat = [r["matched_share"] for r in dr]
        P("ShareRandMin", pct(min(rnd))); P("ShareRandMax", pct(max(rnd)))
        P("ShareMatMin", pct(min(mat))); P("ShareMatMax", pct(max(mat)))
        P("ShareTol", f"{100 * sh['tol']:.0f}")
        P("ShareNseeds", str(len(dr)))
        P("ShareNchanged", str(sum(r["random_cids"] != r["matched_cids"] for r in dr)))
        for r in dr:
            if r["seed"] in SEEDS:
                w = SEEDS[r["seed"]]
                P(f"ShareRand{w}", pct(r["random_share"]))
                P(f"ShareMat{w}", pct(r["matched_share"]))
                P(f"MatRowsMin{w}", f"{min(r['matched_rows']):,}".replace(",", "{,}"))
    # --- P2 attack (random selection) and clean floor, FedAvg, per seed -------
    for s, w in SEEDS.items():
        if s not in P12_SEEDS:
            for k in ("RandBSR", "RandCA", "CleanBSR", "CleanCA"):
                P(f"{k}{w}", "n/r")
            continue
        c = cell(R("postfix_p2", f"p2full_dirichlet_ciciot2023_fedavg_atk1_m0.2_p0.1_fixed_me5_s{s}.json"))
        P(f"RandBSR{w}", f3(c["bsr"] if c else None))
        P(f"RandCA{w}", f3(c["ca"] if c else None))
        c = cell(R("postfix_p1", f"p1full_dirichlet_ciciot2023_fedavg_atk0_m0.0_p0.0_fixed_s{s}.json"))
        P(f"CleanBSR{w}", f3(c["bsr"] if c else None))
        P(f"CleanCA{w}", f3(c["ca"] if c else None))
    # --- calibration cells ------------------------------------------------------
    found = {}
    for path in glob.glob(R("calib_iter6", "calib6_dirichlet_*fedavg_atk1_m0.2_p0.1_fixed*.json")):
        name = os.path.basename(path)
        suf = name.split("_fixed", 1)[1].rsplit("_s", 1)
        stem = VARIANTS.get(suf[0])
        if stem is None:
            continue
        found[(stem, int(suf[1].split(".")[0]))] = cell(path)
    for stem in sorted(set(VARIANTS.values())):
        bs = []
        for s, w in SEEDS.items():
            c = found.get((stem, s))
            if c is None:
                if stem in REQUIRED or any(k[0] == stem for k in found):
                    # run_calib.sh queued E_m=5/10 on seeds 42-46 only, E_m=15 on all ten
                    planned = stem == "SmEfifteen" or s in P12_SEEDS
                    for k in ("CA", "BSR", "Implant", "Share"):
                        P(f"{stem}{k}{w}", "\\PENDING" if planned else "n/r")
                continue
            bs.append(c["bsr"])
            P(f"{stem}CA{w}", f3(c["ca"])); P(f"{stem}BSR{w}", f3(c["bsr"]))
            P(f"{stem}Implant{w}", "--" if c["imp"] is None else str(c["imp"]))
            P(f"{stem}Share{w}", pct(c["share"]) if c["share"] is not None else "\\PENDING")
        if bs:
            P(f"{stem}BSRMin", f3(min(bs))); P(f"{stem}N", str(len(bs)))

    # --- implant dynamics over the calibration cells (iteration 7) ----------------
    imps, maxr, lastr = [], {}, {}
    for (stem, s), c in found.items():
        if c is not None and c["bsr"] > 0.5 and c["imp"] is not None:
            imps.append(c["imp"])
    for stem, w in (("SmEten", "Ten"), ("SmEfifteen", "Fifteen")):
        p = R("calib_iter6", f"calib6_dirichlet_ciciot2023_fedavg_atk1_m0.2_p0.1_fixed"
                             f"{[k for k, v in VARIANTS.items() if v == stem][0]}_s46.json")
        if os.path.exists(p):
            b = json.load(open(p))["history"]["bsr"]
            P(f"SixMaxRound{w}", f3(max(b))); P(f"SixLastRound{w}", f3(b[-1]))
            P(f"SixRoundsAbove{w}", str(sum(x > 0.5 for x in b)))
        else:
            for k in ("MaxRound", "LastRound", "RoundsAbove"):
                P(f"Six{k}{w}", "\\PENDING")
    P("OnsetMin", str(min(imps)) if imps else "\\PENDING")
    P("OnsetMax", str(max(imps)) if imps else "\\PENDING")
    P("OnsetN", str(len(imps)))

    # --- data-only probe of what the attackers poison (iteration 7) ------------
    # results/calib_iter6/s46_probe.json <- experiments/calib_iter6/s46_probe.py
    pp = R("calib_iter6", "s46_probe.json")
    if os.path.exists(pp):
        pr = json.load(open(pp))
        st = pr["trigger_column_stats"]
        out_rng = [k for k, v in st.items()
                   if not (v["min"] <= v["trigger_value"] <= v["max"])]
        P("TrigNcols", str(len(st))); P("TrigNoutRange", str(len(out_rng)))
        P("TrigNearRows", str(sum(pr["near_trigger_rows_per_class"])))
        rows = pr["seeds"]
        npois = [r["n_poisoned"] for r in rows]
        P("PoisRowsMin", str(min(npois))); P("PoisRowsMax", str(max(npois)))
        P("PoisCoverMin", pct(min(r["bsr_test_coverage"] for r in rows)))
        b = pr["class_names"].index("Benign")
        mb = {r["seed"]: r["mal_class_counts"][b] for r in rows}
        P("MalBenignFortySix", str(mb[46]))
        others = {s: v for s, v in mb.items() if s in (42, 43, 44)}
        P("MalBenignImplMin", str(min(others.values())))
        P("MalBenignImplMax", str(max(others.values())))
        P("MalBenignFortyNine", str(mb[49])); P("MalBenignFiftyOne", str(mb[51]))
        dd = {r["seed"]: r["poisoned_by_class"][pr["class_names"].index("DDoS")] / r["n_poisoned"]
              for r in rows}
        P("PoisDDoSFortySix", pct(dd[46]))
        P("PoisDDoSImplMin", pct(min(dd[s] for s in (42, 43, 44))))
    else:
        for k in ("TrigNcols", "TrigNoutRange", "TrigNearRows", "PoisRowsMin", "PoisRowsMax",
                  "PoisCoverMin", "MalBenignFortySix", "MalBenignImplMin", "MalBenignImplMax",
                  "MalBenignFortyNine", "MalBenignFiftyOne", "PoisDDoSFortySix", "PoisDDoSImplMin"):
            P(k, "\\PENDING")

    # --- FoolsGold diagnostic --------------------------------------------------
    for var, vstem in (("base", "Base"), ("norm0", "NormOff"), ("hist0", "HistOff")):
        path = R("foolsgold_diag", f"fgdiag_{var}_trainable_s42.json")
        if not os.path.exists(path):
            for k in ("CA", "KeptMed", "RoundOneKept", "RoundOneCA", "KeptMajorDDoS"):
                P(f"Fg{vstem}{k}", "\\PENDING")
            continue
        d = json.load(open(path))
        h, log, info = d["history"], d["fg_log"], {c["cid"]: c for c in d["clients"]}
        P(f"Fg{vstem}CA", f3(tail(h["accuracy"])))
        P(f"Fg{vstem}RoundOneCA", f3(h["accuracy"][0]))
        P(f"Fg{vstem}KeptMed", f"{np.median([e['kept'] for e in log]):g}")
        P(f"Fg{vstem}RoundOneKept", str(log[0]["kept"]))
        # rows held by the clients FoolsGold keeps (weight > 0) in the last round
        last = log[-1]
        kept = [c for c, wv in zip(last["cids"], last["wv"]) if wv > 1e-3]
        tot = sum(c["rows"] for c in d["clients"])
        P(f"Fg{vstem}KeptRowShare", pct(sum(info[c]["rows"] for c in kept) / tot))
        ddos = [c for c in info if info[c]["major"] == "DDoS"]
        P(f"Fg{vstem}KeptMajorDDoS", f"{sum(c in kept for c in ddos)}")
        P(f"Fg{vstem}NMajorDDoS", f"{len(ddos)}")
        if var == "base":
            mc = [x for e in log[1:] for x in e["max_cos"]]
            P("FgBaseMaxCosMed", f3(float(np.median(mc))))
            P("FgBaseRoundOneMaxCosMed", f3(float(np.median(log[0]["max_cos"]))))
    open(OUT, "w").write("\n".join(L) + "\n")
    print(f"wrote {OUT} ({len(L) - 1} macros)")


if __name__ == "__main__":
    main()
