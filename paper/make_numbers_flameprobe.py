#!/usr/bin/env python3
"""Macros for the FLAME mechanism probe (iteration 29; exploratory).

Source: results/flame_probe/flame_iid_s42.jsonl, written by experiments/flame_probe/flame_probe.py
(one attacked IID FLAME run in the defect arm, seed 42, logging only). Writes numbers_flameprobe.tex
with \\fp* macros; missing input -> \\PENDING.

"Early" = round 1; "late" = rounds 6..last. Cosines are means over pairs (attacker-honest "mh",
honest-honest "hh"), over the full transmitted vector or over the trainable coordinates.
"""
import json
import os

import numpy as np

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)
SRC = os.path.join(ROOT, "results", "flame_probe", "flame_iid_s42.jsonl")
OUT = os.path.join(HERE, "numbers_flameprobe.tex")
LATE = 6


def main():
    m = {}
    rows = []
    if os.path.exists(SRC):
        rows = [json.loads(l) for l in open(SRC) if l.strip()]
    P = lambda k, v: m.__setitem__(k, v)
    pend = "\\PENDING"
    if not rows:
        for k in ("Rounds", "MhFirst", "HhFirst", "MhLate", "HhLate", "TrMhLate", "TrHhLate",
                  "ShareHonFirst", "ShareHonLate", "ShareMal", "FirstAdmit", "FullAdmitRounds",
                  "TrAdmitRounds", "LateFrom", "AdmitWindow", "AdmitInWindow"):
            P(k, pend)
    else:
        late = [r for r in rows if r["round"] >= LATE]
        mal = lambda r: np.array(r["mal"], dtype=bool)
        share = lambda r, w: float(np.mean(np.array(r["buf_share"])[mal(r) == w]))
        P("Rounds", str(len(rows)))
        P("LateFrom", str(LATE))
        P("MhFirst", f"{rows[0]['full']['mh']:.3f}")
        P("HhFirst", f"{rows[0]['full']['hh']:.3f}")
        P("MhLate", f"{np.mean([r['full']['mh'] for r in late]):.3f}" if late else pend)
        P("HhLate", f"{np.mean([r['full']['hh'] for r in late]):.3f}" if late else pend)
        P("TrMhLate", f"{np.mean([r['trainable']['mh'] for r in late]):.2f}" if late else pend)
        P("TrHhLate", f"{np.mean([r['trainable']['hh'] for r in late]):.2f}" if late else pend)
        P("ShareHonFirst", f"{share(rows[0], False):.3f}")
        P("ShareHonLate", f"{np.mean([share(r, False) for r in late]):.3f}" if late else pend)
        P("ShareMal", f"{np.mean([share(r, True) for r in rows]):.3f}")
        adm_full = [any(mal(r)[i] for i in r["full"]["admitted"]) for r in rows]
        adm_tr = [any(mal(r)[i] for i in r["trainable"]["admitted"]) for r in rows]
        P("FullAdmitRounds", str(int(sum(adm_full))))
        P("TrAdmitRounds", str(int(sum(adm_tr))))
        P("FirstAdmit", str(rows[adm_full.index(True)]["round"]) if any(adm_full) else "--")
        # rounds from the first full-vector admission to the end, and how many of them admit
        k = adm_full.index(True) if any(adm_full) else len(rows)
        P("AdmitWindow", str(len(rows) - k))
        P("AdmitInWindow", str(int(sum(adm_full[k:]))))
    lines = ["% generated by paper/make_numbers_flameprobe.py -- do not edit"]
    lines += [f"\\providecommand{{\\fp{k}}}{{{v}}}" for k, v in sorted(m.items())]
    open(OUT, "w").write("\n".join(lines) + "\n")
    print(f"wrote {OUT} ({len(m)} macros)")


if __name__ == "__main__":
    main()
