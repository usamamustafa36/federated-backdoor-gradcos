#!/usr/bin/env python3
"""Macros for the mechanism of the fixed-arm FLTrust IID shutdown (iteration 21).

Reads
  results/fltrust_shutdown/replay_{iid,dirichlet}_s*.json
      <- experiments/fltrust_shutdown/replay.py (CPU replay of a clean P3 cell, exact
         P3 config, per-round trust cosines + RNG-neutral counterfactual root updates)
  results/fltrust_shutdown/natroot_*.json
      <- experiments/fltrust_shutdown/run_natroot.sh (closed loop, fixed arm, root
         drawn from the training distribution; exploratory)
  results/postfix_p3/p3trainable_iid_*fltrust_atk0*.json (the P3 originals)
and writes paper/numbers_fltshut.tex (\\fs... macros; generated, DO NOT EDIT).
"""
from __future__ import annotations

import glob
import json
import os
import re

import numpy as np

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
RES = os.path.join(ROOT, "results", "fltrust_shutdown")
OUT = os.path.join(ROOT, "paper", "numbers_fltshut.tex")
PEND = "\\PENDING"


def f2(x):
    return f"{x:.2f}".replace("-", "$-$") if False else f"{x:.2f}"


def shut_round(flags):
    """First round from which every later round flags everyone (1-based) or None."""
    allx = [bool(f) for f in flags]
    return next((i + 1 for i in range(len(allx)) if all(allx[i:])), None)


def main():
    L = ["% generated by paper/make_numbers_fltshut.py -- DO NOT EDIT"]
    P = lambda k, v: L.append(f"\\providecommand{{\\fs{k}}}{{{v}}}")
    reps = {}
    for p in sorted(glob.glob(os.path.join(RES, "replay_*_s*.json"))):
        d = json.load(open(p))
        reps[(d["partition"], d["seed"])] = d
    iid = [d for (part, _), d in sorted(reps.items()) if part == "iid"]
    P("ReplayN", str(len(iid)) if iid else PEND)
    if iid:
        shut, shut_p3, sh_rows, pre_rows = [], [], [], []
        for d in iid:
            R = d["rounds"]
            n = len(d["rounds"][0]["cos"])
            sr = shut_round([r["flagged"] == n for r in R])
            shut.append(sr)
            p3 = glob.glob(os.path.join(ROOT, "results", "postfix_p3",
                           f"p3trainable_iid_ciciot2023_fltrust_atk0_*_s{d['seed']}.json"))
            if p3:
                f = json.load(open(p3[0]))["history"]["false_positive_rate"]
                shut_p3.append(shut_round([x >= 0.99 for x in f]))
            if sr is not None:
                sh_rows += [r for r in R if r["round"] >= sr]
                pre_rows += [r for r in R if r["round"] < sr]
        P("ReplaySeeds", ", ".join(str(d["seed"]) for d in iid))
        P("ReplayRounds", str(min(len(d["rounds"]) for d in iid)))
        P("ShutRounds", " and ".join(str(s) for s in shut) if all(shut) else PEND)
        P("ShutMatchesPthree", "yes" if shut_p3 == shut and all(shut) else "no")
        P("ShutNrounds", str(len(sh_rows)))
        if sh_rows:
            cat = lambda key: np.concatenate([np.atleast_1d(r[key]) for r in sh_rows])
            P("BalCosLo", f"{cat('cos').min():.2f}")
            P("BalCosHi", f"{cat('cos').max():.2f}")
            P("RepCosHi", f"{cat('cf_bal_rep_cos').max():.2f}")
            P("NatCosLo", f"{cat('cf_nat_cos').min():.2f}")
            P("NatCosHi", f"{cat('cf_nat_cos').max():.2f}")
            P("NatWCosLo", f"{cat('cf_nat_w_cos').min():.2f}")
            P("BalWCosHi", f"{cat('cf_bal_w_cos').max():.2f}")
            P("RepToBalMin", f"{cat('cf_bal_rep_cos_to_g0').min():.2f}")
            P("NatToBalLo", f"{cat('cf_nat_cos_to_g0').min():.2f}")
            P("NatToBalHi", f"{cat('cf_nat_cos_to_g0').max():.2f}")
            # where the negative inner product lives: share of the summed negative
            # per-tensor contributions carried by the LSTM recurrent weights
            shares = []
            for r in sh_rows:
                neg = {k: v for k, v in r["dot_by_tensor"].items() if v < 0}
                tot = sum(neg.values())
                if tot < 0:
                    shares.append(neg.get("lstm.weight_hh_l0", 0.0) / tot)
            P("LstmShareMin", f"{100 * min(shares):.0f}" if shares else PEND)
            # root update does not collapse: ||g0|| in shutdown rounds vs before
            g_sh = [r["g0_norm"] for r in sh_rows]
            g_pre = [r["g0_norm"] for r in pre_rows]
            P("GzeroShLo", f"{min(g_sh):.2f}"); P("GzeroShHi", f"{max(g_sh):.2f}")
            P("GzeroPreLo", f"{min(g_pre):.2f}"); P("GzeroPreHi", f"{max(g_pre):.2f}")
            cn_sh = [float(np.median(r["client_norms"])) for r in sh_rows]
            cn_pre = [float(np.median(r["client_norms"])) for r in pre_rows]
            P("CliShLo", f"{min(cn_sh):.1f}"); P("CliPreHi", f"{max(cn_pre):.1f}")
            # before the shutdown the natural-root cosines are higher every round
            P("PreNatAboveBal", "yes" if all(min(r["cf_nat_cos"]) > max(r["cos"]) for r in pre_rows) else "no")
            P("PreBalCosLo", f"{min(min(r['cos']) for r in pre_rows):.2f}")
    # contrast: Dirichlet replay
    dirs = [d for (part, _), d in sorted(reps.items()) if part == "dirichlet"]
    if dirs:
        R = dirs[0]["rounds"]
        n = len(R[0]["cos"])
        P("DirRounds", str(len(R)))
        P("DirFullShutRounds", str(sum(r["flagged"] == n for r in R)))
        P("DirMaxFlagged", str(max(r["flagged"] for r in R)))
        P("DirClients", str(n))
    else:
        for k in ("DirRounds", "DirFullShutRounds", "DirMaxFlagged", "DirClients"):
            P(k, PEND)
    # closed loop with a natural root (exploratory)
    for kind, tag in (("atk0", "Clean"), ("atk1", "Atk")):
        files = sorted(glob.glob(os.path.join(RES, f"natroot_iid_ciciot2023_fltrust_{kind}_*.json")))
        hs = []
        for p in files:
            if os.path.getsize(p) == 0:
                continue
            hs.append(json.load(open(p))["history"])
        P(f"Nat{tag}N", str(len(hs)))
        if hs:
            fpr = [float(np.mean(h["false_positive_rate"][-5:])) for h in hs]
            ca = [float(np.mean(h["accuracy"][-5:])) for h in hs]
            shut_runs = sum(shut_round([x >= 0.99 and (kind == "atk0" or (y is not None and y >= 0.99))
                                        for x, y in zip(h["false_positive_rate"], h["detection_rate"])]) is not None
                            for h in hs)
            P(f"Nat{tag}Fpr", f"{np.mean(fpr):.3f}")
            P(f"Nat{tag}CA", f"{np.mean(ca):.3f}")
            P(f"Nat{tag}Shut", str(shut_runs))
            if kind == "atk1":
                dr = [float(np.mean(h["detection_rate"][-5:])) for h in hs]
                P(f"Nat{tag}Dr", f"{np.mean(dr):.3f}")
        else:
            for k in ("Fpr", "CA", "Shut", "Dr"):
                P(f"Nat{tag}{k}", PEND)
    open(OUT, "w").write("\n".join(L) + "\n")
    print(f"wrote {OUT} ({len(L) - 1} macros)")


if __name__ == "__main__":
    main()
