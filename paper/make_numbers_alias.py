"""Macros for the round-1 aliasing note (iteration 5) -> paper/numbers_alias.tex.

Sources (all generated, nothing typed):
  results/round1_alias/trace.json          what round 1 does with / without the copy
  results/round1_alias/outcome_*.json      paired bug-vs-fix runs on a tiny config
  results/postfix_p1/*atk0*.json           the campaign's own per-round diagnostics

Macro prefix \\ra. Missing inputs print as \\PENDING.
"""
from __future__ import annotations

import glob
import json
import math
import os
from collections import defaultdict

import numpy as np

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
RA = os.path.join(ROOT, "results", "round1_alias")
P1 = os.path.join(ROOT, "results", "postfix_p1")
OUT = os.path.join(ROOT, "paper", "numbers_alias.tex")
DN = {"fedavg": "Fedavg", "foolsgold": "Foolsgold", "fltrust": "Fltrust",
      "flame": "Flame", "krum": "Krum"}
MN = {"full": "Full", "trainable": "Tr"}
AN = {0: "Clean", 1: "Atk"}


def fmt(x, nd=3, sign=False):
    if x is None or (isinstance(x, float) and (math.isnan(x) or math.isinf(x))):
        return "\\PENDING"
    return f"{x:+.{nd}f}" if sign else f"{x:.{nd}f}"


def main():
    L = ["% Generated by paper/make_numbers_alias.py -- do not edit."]
    put = lambda k, v: L.append(f"\\providecommand{{\\{k}}}{{{v}}}")

    # ---- trace ---------------------------------------------------------
    tp = os.path.join(RA, "trace.json")
    if os.path.exists(tp):
        t = json.load(open(tp))
        for arm, nm in (("bug", "Bug"), ("fix", "Fix")):
            st = [r for r in t[arm]["starts"] if r["round"] == 1]
            st2 = [r for r in t[arm]["starts"] if r["round"] == 2]
            ref = [r for r in t[arm]["refs"] if r["round"] == 1][0]
            put(f"ra{nm}LastStartDist", fmt(st[-1]["start_dist_to_round_global"]))
            put(f"ra{nm}LastStartCount", str(st[-1]["start_counter_sum"]))
            put(f"ra{nm}RefToLast", fmt(ref["ref_dist_to_last_client"]))
            put(f"ra{nm}RoundTwoCount", str(st2[0]["start_counter_sum"]))
            put(f"ra{nm}OwnBatchesFirst", str(st[0]["trained_counter_sum"] - st[0]["start_counter_sum"]))
        put("raTraceClients", str(len([r for r in t["bug"]["starts"] if r["round"] == 1])))
    # ---- campaign diagnostics: round 1 vs rounds 2.. -------------------
    acc = defaultdict(list)
    for p in glob.glob(os.path.join(P1, "*dirichlet*atk0*.json")):
        try:
            h = json.load(open(p))["history"]
        except (OSError, json.JSONDecodeError, KeyError):
            continue
        for k, nm in (("pair_cos_full", "CosFull"), ("pair_cos_sig", "CosSig"),
                      ("buffer_norm_share", "NormShare"), ("buffer_dist_share", "DistShare")):
            v = [x for x in h.get(k, []) if x is not None and not math.isnan(x)]
            if len(v) < 2:
                continue
            acc[nm + "Rone"].append(v[0])
            acc[nm + "All"].append(float(np.mean(v)))
            acc[nm + "Rtwo"].append(float(np.mean(v[1:])))
    for k, v in acc.items():
        put(f"raPone{k}", fmt(float(np.median(v))))
    put("raPoneRuns", str(len(acc.get("CosFullRone", []))) if acc else "\\PENDING")

    # ---- tiny paired outcome --------------------------------------------
    rows = []
    for p in glob.glob(os.path.join(RA, "outcome_*.json")):
        try:
            rows += json.load(open(p))
        except (OSError, json.JSONDecodeError):
            pass
    by = {(r["mode"], r["defense"], r["attack"], r["seed"], r["fix"]): r for r in rows}
    put("raTinyRuns", str(len(rows)))
    seeds = sorted({r["seed"] for r in rows})
    put("raTinySeeds", str(len(seeds)) if seeds else "\\PENDING")
    maxabs = defaultdict(float)
    for d in DN:
        for a in (0, 1):
            for m in MN:
                for met in ("CA", "FPR", "BSR"):
                    diffs = [by[(m, d, a, s, True)][met] - by[(m, d, a, s, False)][met]
                             for s in seeds if (m, d, a, s, True) in by and (m, d, a, s, False) in by
                             and not math.isnan(by[(m, d, a, s, True)][met])
                             and not math.isnan(by[(m, d, a, s, False)][met])]
                    put(f"raD{met}{DN[d]}{MN[m]}{AN[a]}",
                        fmt(float(np.mean(diffs)), sign=True) if diffs else "\\PENDING")
                    if diffs:
                        maxabs[met] = max(maxabs[met], max(abs(x) for x in diffs))
                # round-1 diagnostics in each code path
                for fx, nm in ((False, "Bug"), (True, "Fix")):
                    v = [by[(m, d, a, s, fx)]["pair_cos_full_r1"] for s in seeds
                         if (m, d, a, s, fx) in by]
                    put(f"raCosFullRone{DN[d]}{MN[m]}{AN[a]}{nm}",
                        fmt(float(np.mean(v))) if v else "\\PENDING")
            # A/B arm effect (trainable - full) under each code path
            for met in ("CA", "FPR", "BSR"):
                for fx, nm in ((False, "Bug"), (True, "Fix")):
                    v = [by[("trainable", d, a, s, fx)][met] - by[("full", d, a, s, fx)][met]
                         for s in seeds if ("trainable", d, a, s, fx) in by
                         and ("full", d, a, s, fx) in by
                         and not math.isnan(by[("trainable", d, a, s, fx)][met])
                         and not math.isnan(by[("full", d, a, s, fx)][met])]
                    put(f"raArm{met}{DN[d]}{AN[a]}{nm}",
                        fmt(float(np.mean(v)), sign=True) if v else "\\PENDING")
    for met in ("CA", "FPR", "BSR"):
        put(f"raMaxAbs{met}", fmt(maxabs[met]) if met in maxabs else "\\PENDING")
    # round-1 cosine over all tiny rows, per code path
    for fx, nm in ((False, "Bug"), (True, "Fix")):
        v = [r["pair_cos_full_r1"] for r in rows if r["fix"] == fx]
        w = [r["pair_cos_full_r2on"] for r in rows if r["fix"] == fx]
        put(f"raTinyCosFullRone{nm}", fmt(float(np.median(v))) if v else "\\PENDING")
        put(f"raTinyCosFullRtwo{nm}", fmt(float(np.median(w))) if w else "\\PENDING")
    # campaign-scale replay (fixed code, same seed) vs the campaign cell
    cp = os.path.join(RA, "campaign_replay.json")
    if os.path.exists(cp):
        reps = json.load(open(cp))
    else:
        reps = []
    seen = {(r["defense"], r["mode"], r["attack"]): r for r in reps}
    for d in ("fedavg", "foolsgold"):
        for m in MN:
            for a in (0, 1):
                r = seen.get((d, m, a))
                stem = f"raRep{DN[d]}{MN[m]}{AN[a]}"
                for met in ("CA", "FPR", "BSR"):
                    bug = r[met + "_bug"] if r else float("nan")
                    fix = r[met + "_fix"] if r else float("nan")
                    put(f"{stem}{met}Bug", fmt(bug))
                    put(f"{stem}{met}Fix", fmt(fix))
                    put(f"{stem}{met}Diff", fmt(fix - bug, sign=True))
    # replay arm effects (trainable - full) under the fix, vs the campaign's own s42
    for a in (0, 1):
        f, t = seen.get(("foolsgold", "full", a)), seen.get(("foolsgold", "trainable", a))
        for met in ("CA", "FPR", "BSR"):
            for path in ("bug", "fix"):
                v = (t[f"{met}_{path}"] - f[f"{met}_{path}"]) if (f and t) else float("nan")
                put(f"raRepArmFoolsgold{AN[a]}{met}{path.capitalize()}", fmt(v, sign=True))
    open(OUT, "w").write("\n".join(L) + "\n")
    print(f"wrote {OUT}: {len(L) - 1} macros, {len(rows)} tiny rows")


if __name__ == "__main__":
    main()
