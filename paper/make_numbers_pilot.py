"""Attack-calibration pilot -> paper/numbers_pilot.tex (\ap... macros).

Source: results/pilot_attack_iter4/pilot_fedavg_{partition}_{cell}_s42.json, written by
experiments/attack_pilot/pilot.py (iteration 4). Plain FedAvg, seed 42, P1 scale.
Metrics follow the paper: CA and BSR are means over the last five rounds; the
malicious/honest trainable-norm ratio is the median over rounds; "implant round" is
the first round with BSR > 0.5 (\\ensuremath{-} if none). Missing cells -> \\PENDING.
"""
from __future__ import annotations

import json
import math
import os

import numpy as np

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
RES = os.path.join(ROOT, "results", "pilot_attack_iter4")
OUT = os.path.join(ROOT, "paper", "numbers_pilot.tex")
TAIL = 5

# (partition, cell, macro stem)
CELLS = [
    ("dirichlet", "clean", "DirClean"), ("dirichlet", "cleanx2", "DirCleanXtwo"),
    ("dirichlet", "p1", "DirPone"), ("dirichlet", "p03", "DirPthree"),
    ("dirichlet", "p05", "DirPfive"), ("dirichlet", "m03p03", "DirMthree"),
    ("dirichlet", "x2", "DirXtwo"), ("dirichlet", "boost5", "DirBoostFive"),
    ("dirichlet", "ep2", "DirEtwo"), ("dirichlet", "ep3", "DirEthree"),
    ("dirichlet", "ep5", "DirEfive"),
    ("iid", "clean", "IidClean"), ("iid", "p1", "IidPone"),
    ("iid", "ep3", "IidEthree"), ("iid", "ep5", "IidEfive"),
]


def tail(xs):
    xs = [x for x in xs[-TAIL:] if x is not None and not math.isnan(x)]
    return float(np.mean(xs)) if xs else float("nan")


def f3(x):
    return "\\PENDING" if x is None or math.isnan(x) else f"{x:.3f}"


def main():
    lines = ["% Generated by paper/make_numbers_pilot.py from results/pilot_attack_iter4/. DO NOT EDIT."]
    for part, cell, stem in CELLS:
        fn = os.path.join(RES, f"pilot_fedavg_{part}_{cell}_s42.json")
        if os.path.exists(fn):
            d = json.load(open(fn))
            h = d["history"]
            ca, bsr = tail(h["accuracy"]), tail(h["bsr"])
            nr = [x for x in h["mal_norm_ratio"] if x is not None and not math.isnan(x)]
            nr = float(np.median(nr)) if nr else float("nan")
            imp = next((r for r, b in zip(h["rounds"], h["bsr"]) if b > 0.5), None)
            npois = d.get("n_poisoned_rows")
            imp_s = "--" if imp is None else str(imp)
            nr_s = "--" if math.isnan(nr) else f"{nr:.2f}"
        else:
            ca = bsr = float("nan")
            imp_s = nr_s = "\\PENDING"
            npois = None
        np_s = "\\PENDING" if npois is None else f"{npois:,}".replace(",", "{,}")
        lines += [
            f"\\providecommand{{\\ap{stem}CA}}{{{f3(ca)}}}",
            f"\\providecommand{{\\ap{stem}BSR}}{{{f3(bsr)}}}",
            f"\\providecommand{{\\ap{stem}Norm}}{{{nr_s}}}",
            f"\\providecommand{{\\ap{stem}Implant}}{{{imp_s}}}",
            f"\\providecommand{{\\ap{stem}Npois}}{{{np_s}}}",
        ]
    open(OUT, "w").write("\n".join(lines) + "\n")
    print(f"wrote {OUT}")


if __name__ == "__main__":
    main()
