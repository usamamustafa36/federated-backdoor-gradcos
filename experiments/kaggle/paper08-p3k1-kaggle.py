import glob, os, shutil, subprocess, sys, tarfile, time
T0 = time.time(); STOP_LAUNCH = 11.0 * 3600; HARD = 11.6 * 3600
W = "/kaggle/working"; REPO = f"{W}/p08"; LANES = int(os.environ.get("LANES", "6"))
subprocess.run([sys.executable, "-m", "pip", "install", "-q", "flwr==1.30.0"], check=False)
tarfile.open(glob.glob("/kaggle/input/**/p08code.tgz", recursive=True)[0]).extractall(REPO)
os.makedirs(f"{REPO}/data/ciciot2023", exist_ok=True)
for n in ("train.parquet", "test.parquet"):
    os.symlink(glob.glob(f"/kaggle/input/**/{n}", recursive=True)[0], f"{REPO}/data/ciciot2023/{n}")
os.makedirs(f"{REPO}/results/kgt_k1", exist_ok=True); os.makedirs(f"{REPO}/results/postfix_p3", exist_ok=True)
import torch; NG = max(1, torch.cuda.device_count())
print(torch.__version__, [torch.cuda.get_device_name(i) for i in range(torch.cuda.device_count())], flush=True)
jobs = []
for l in K1.split("\n"):
    if not l.strip(): continue
    st, me, b, mode, d, s = l.split()
